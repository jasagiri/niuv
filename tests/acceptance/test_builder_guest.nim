## Acceptance (not part of test_all): the real kite starts the real builder
## image, and niuv builds a Nim bin and a Gleam app in the guest (NIV-27, NIV-28,
## NIV-29, NIV-31). Run by hand; it takes minutes (each guest start applies the
## image's layers) and needs the machine's kite, a signed builder image in
## kite's store, a signed kernel and initramfs, and gleam's Hex copy.
##
## It fails, it does not skip, when the environment is not set:
##   NIUV_ACC_KITE_DIR     the directory that holds the `kite` executable
##   NIUV_ACC_KITE_HOME    the HOME kite runs with (its ~/.kite store and trust file)
##   NIUV_ACC_IMAGE        NAME@sha256:<digest> of the builder image
##   NIUV_ACC_SIGNATURE    the image's signature file
##   NIUV_ACC_KERNEL, NIUV_ACC_INITRD   the signed kernel and initramfs
##   NIUV_ACC_HEX          gleam's Hex packages directory (.../hex/hexpm/packages)
##   NIUV_ACC_SCRATCH      a directory outside the repository for the workspace and outputs
##
##   nim c -r --opt:speed tests/acceptance/test_builder_guest.nim

import std/[algorithm, options, os, sequtils, strutils, unittest]
import ../../src/niuv/[artifact, cli, errors, inbuilder, lock, manifest]

proc need(name: string): string =
  result = getEnv(name)
  doAssert result.len > 0, name & " is not set (see the head of this file)"

const
  linux = "aarch64-linux-musl"
  nimV = "2.2.12"
  gleamV = "1.19.1"
  otpV = "29.1.1"
  gleamManifest = """# This file was generated by Gleam
packages = [
  { name = "gleam_stdlib", version = "1.0.5", build_tools = ["gleam"], requirements = [], otp_app = "gleam_stdlib", source = "hex", outer_checksum = "CEE5B6C076A85B45F60C585F4316C63EC8B7127C119D5738C3958A9C4D50404E" },
]

[requirements]
gleam_stdlib = { version = ">= 1.0.0 and < 2.0.0" }
"""

proc pkgToml(name, extra: string): string =
  "[package]\nname = \"" & name & "\"\nversion = \"0.1.0\"\nlicense = \"Apache-2.0\"\n" & extra

proc makeWorkspace(dir: string) =
  createDir(dir / "demo" / "src")
  createDir(dir / "demo" / "child")
  createDir(dir / "broken" / "child")
  createDir(dir / "broken" / "src")
  writeFile(dir / "demo" / "niuv.toml", pkgToml("demo", "\n[nim]\n[[nim.bin]]\nname = \"demo-hello\"\nmain = \"child/hello.nim\"\n\n[gleam]\n"))
  writeFile(dir / "demo" / "src" / "placeholder.nim", "discard\n")
  writeFile(dir / "demo" / "child" / "hello.nim", "echo \"built in the guest\"\n")
  writeFile(dir / "demo" / "gleam.toml", "name = \"demo\"\nversion = \"0.1.0\"\ntarget = \"erlang\"\n\n[dependencies]\ngleam_stdlib = \">= 1.0.0 and < 2.0.0\"\n")
  writeFile(dir / "demo" / "manifest.toml", gleamManifest)
  writeFile(dir / "demo" / "src" / "demo.gleam", "import gleam/int\n\npub fn answer() -> String {\n  int.to_string(42)\n}\n")
  writeFile(dir / "broken" / "niuv.toml", pkgToml("broken", "\n[nim]\n[[nim.bin]]\nname = \"broken-bin\"\nmain = \"child/b.nim\"\n"))
  writeFile(dir / "broken" / "src" / "placeholder.nim", "discard\n")
  writeFile(dir / "broken" / "child" / "b.nim", "this is not nim (\n")
  writeFile(dir / "niuv.workspace.toml", "[workspace]\nmembers = [\"demo\", \"broken\"]\n[tools.nim]\nversion = \"" & nimV &
    "\"\n[tools.gleam]\nversion = \"" & gleamV & "\"\n[tools.erlang]\nversion = \"" & otpV & "\"\n[tools.kite]\nversion = \"0.1.0\"\n")

proc guestFlags(): seq[string] =
  @["--signature", need("NIUV_ACC_SIGNATURE"), "--kernel", need("NIUV_ACC_KERNEL"), "--initrd", need("NIUV_ACC_INITRD"),
    "--hex-cache", need("NIUV_ACC_HEX")]

proc cleanRuns() =
  ## The guests this process started leave their root file systems in kite's store.
  let runs = need("NIUV_ACC_KITE_HOME") / ".kite" / "runs"
  for kind, path in walkDir(runs):
    if kind == pcDir and ("niuv-build-" & $getCurrentProcessId() & "-") in path.extractFilename:
      removeDir(path)

suite "N-K4-2 acceptance: the builder guest":
  test "Given the signed image, When a Nim bin and a Gleam app are built in the guest, Then the host re-checks and accepts the output":
    let scratch = need("NIUV_ACC_SCRATCH") / "niuv-acc-guest"
    removeDir(scratch)
    makeWorkspace(scratch)
    let w = scratch / "niuv.workspace.toml"
    let oldPath = getEnv("PATH")
    let oldHome = getEnv("HOME")
    putEnv("PATH", need("NIUV_ACC_KITE_DIR") & ":" & oldPath)
    putEnv("HOME", need("NIUV_ACC_KITE_HOME"))
    try:
      # The host's own lock pins kite (NIV-27).
      let hostLock = runCli(@["lock", "--workspace", w])
      check hostLock.code == 0
      # The guest locks the Linux tools; the host recomputes the rest and keeps the file.
      let lk = runCli(@["lock", "--workspace", w, "--target", linux, "--in-builder", "--builder", need("NIUV_ACC_IMAGE"),
                        "--stage", scratch / "stage"] & guestFlags())
      echo lk.stdout, lk.stderr
      check lk.code == 0
      let targetLock = readLockFile(scratch / ("niuv." & linux & ".lock")).get
      check targetLock.builder.get.image == need("NIUV_ACC_IMAGE")
      check targetLock.tools.mapIt(it.name).sorted == @["erlang", "gleam", "nim"]
      # Build.
      let b = runCli(@["build", "demo", "--workspace", w, "--target", linux, "--in-builder", "--out", scratch / "out",
                       "--stage", scratch / "stage"] & guestFlags())
      echo b.stdout, b.stderr
      check b.code == 0
      let m = decodeManifest(readFile(scratch / "out" / "niuv.manifest.cbor")).get
      check m.formatVersion == 2
      check m.target == linux
      check m.otpVersion == otpV
      check m.entries.anyIt(it.kind == akNimChild and it.name == "demo-hello")
      check m.entries.anyIt(it.kind == akBeam and it.name == "demo")
      check m.entries.anyIt(it.kind == akBeam and it.name == "gleam@int")
      check fileExists(scratch / "out" / "niuv.sbom.cdx.json")
      # The Nim output is a Linux arm64 executable (ELF, e_machine 183), not a Mach-O.
      let elf = readFile(scratch / "out" / "demo-hello")
      check elf[0 ..< 4] == "\x7fELF"
      check ord(elf[18]) == 183
      # The host re-hashes: one changed byte in the output is refused.
      let want = Expectation(package: "demo", version: "0.1.0", target: linux, bins: @["demo-hello"], pinnedOtp: otpV)
      check verifyBuilderOutput(scratch / "out", want).isOk
      var tampered = elf
      tampered[tampered.len div 2] = chr(ord(tampered[tampered.len div 2]) xor 1)
      writeFile(scratch / "out" / "demo-hello", tampered)
      check verifyBuilderOutput(scratch / "out", want).isErr
      # A package that does not compile in the guest: the guest ends with a status, the host refuses.
      let bad = runCli(@["build", "broken", "--workspace", w, "--target", linux, "--in-builder", "--out", scratch / "out-broken",
                         "--stage", scratch / "stage"] & guestFlags())
      echo bad.stdout, bad.stderr
      check bad.code != 0
      check "status" in bad.stderr
    finally:
      putEnv("PATH", oldPath)
      putEnv("HOME", oldHome)
      cleanRuns()
