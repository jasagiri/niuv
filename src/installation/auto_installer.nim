## Auto-installation module for niuv
## Provides robust PATH-independent installation across platforms

import std/[os, strutils, strformat, terminal, osproc, parsecfg]
import ../cli, ../utils

type
  InstallMethod* = enum
    LocalBin,      # ~/.local/bin
    UserBin,       # ~/bin  
    SystemBin,     # /usr/local/bin
    CurrentPath    # Add current directory to PATH

  ShellType* = enum
    Bash, Zsh, Fish, Tcsh, Unknown

  InstallationResult* = object
    success*: bool
    `method`*: InstallMethod
    path*: string
    message*: string

const
  STANDARD_PATHS = [
    "/usr/bin", "/bin", "/usr/sbin", "/sbin", "/usr/local/bin"
  ]

proc detectShellType(): ShellType =
  ## Detect user's shell type with fallback detection
  # Try SHELL environment variable first
  let shellEnv = getEnv("SHELL", "")
  if shellEnv != "":
    if "zsh" in shellEnv: return Zsh
    if "bash" in shellEnv: return Bash
    if "fish" in shellEnv: return Fish
    if "tcsh" in shellEnv or "csh" in shellEnv: return Tcsh
  
  # Try parent process name as fallback
  try:
    let (output, _) = execCmdEx("ps -o comm= -p $PPID")
    let parentProcess = output.strip()
    if "zsh" in parentProcess: return Zsh
    if "bash" in parentProcess: return Bash
    if "fish" in parentProcess: return Fish
    if "tcsh" in parentProcess or "csh" in parentProcess: return Tcsh
  except:
    discard
  
  return Unknown

proc getShellConfigFile(shell: ShellType): string =
  ## Get primary configuration file for shell
  case shell
  of Bash:
    # Prefer .bash_profile if it exists, otherwise .bashrc
    let bashProfile = expandTilde("~/.bash_profile")
    let bashrc = expandTilde("~/.bashrc")
    if fileExists(bashProfile): bashProfile else: bashrc
  of Zsh:
    expandTilde("~/.zshrc")
  of Fish:
    let fishConfig = expandTilde("~/.config/fish/config.fish")
    # Ensure fish config directory exists
    let fishDir = expandTilde("~/.config/fish")
    if not dirExists(fishDir):
      createDir(fishDir)
    fishConfig
  of Tcsh:
    expandTilde("~/.tcshrc")
  of Unknown:
    ""

proc ensurePathExists(path: string): bool =
  ## Ensure directory exists, create if necessary
  try:
    if not dirExists(path):
      createDir(path)
    return true
  except:
    return false

proc isExecutableInPath(name: string): bool =
  ## Check if executable is available in PATH (robust version)
  # Use which/where command with fallback to manual search
  try:
    when defined(windows):
      let (_, code) = execCmdEx(&"where {name}")
    else:
      let (_, code) = execCmdEx(&"which {name}")
    return code == 0
  except:
    # Fallback: manually check PATH
    let pathEnv = getEnv("PATH", "")
    for dir in pathEnv.split(PathSep):
      if dir != "":
        let execPath = dir / name
        if fileExists(execPath):
          return true
    return false

proc createNiuvWrapper(targetPath: string, niuvExecutable: string): bool =
  ## Create a robust niuv wrapper script
  let wrapperContent = when defined(windows): 
    &"""@echo off
setlocal
set "NIUV_ORIGINAL_PATH=%PATH%"
set "PATH={STANDARD_PATHS.join(";")};%PATH%"
"{niuvExecutable}" %*
endlocal
"""
  else:
    &"""#!/bin/bash
# niuv wrapper - auto-generated by niuv auto-installer
# Ensures proper PATH for niuv execution

# Set standard PATH to avoid command not found issues
export PATH="{STANDARD_PATHS.join(":")}":/usr/local/bin:$HOME/.nimble/bin:$HOME/.choosenim/toolchains/nim-2.2.4/bin:$PATH

# Find project root by looking for niuv.toml
find_project_root() {{
    local dir="$PWD"
    while [ "$dir" != "/" ]; do
        if [ -f "$dir/niuv.toml" ]; then
            echo "$dir"
            return 0
        fi
        dir="${{dir%/*}}"
    done
    return 1
}}

# If we're in a niuv project, ensure we're at project root
if PROJECT_ROOT=$(find_project_root); then
    cd "$PROJECT_ROOT"
fi

# Execute niuv with all arguments
exec "{niuvExecutable}" "$@"
"""

  try:
    writeFile(targetPath, wrapperContent)
    when not defined(windows):
      setFilePermissions(targetPath, {fpUserExec, fpUserRead, fpUserWrite, fpGroupRead, fpOthersRead})
    return true
  except:
    return false

proc installToLocalBin(niuvExecutable: string): InstallationResult =
  ## Install to ~/.local/bin (preferred method)
  let localBin = expandTilde("~/.local/bin")
  let targetPath = localBin / "niuv"
  
  if not ensurePathExists(localBin):
    return InstallationResult(
      success: false,
      `method`: LocalBin,
      path: localBin,
      message: "Failed to create ~/.local/bin directory"
    )
  
  if createNiuvWrapper(targetPath, niuvExecutable):
    return InstallationResult(
      success: true,
      `method`: LocalBin,
      path: targetPath,
      message: &"Installed to {targetPath}. Add ~/.local/bin to your PATH if needed."
    )
  else:
    return InstallationResult(
      success: false,
      `method`: LocalBin,
      path: targetPath,
      message: "Failed to create niuv wrapper"
    )

proc installToUserBin(niuvExecutable: string): InstallationResult =
  ## Install to ~/bin (alternative method)
  let userBin = expandTilde("~/bin")
  let targetPath = userBin / "niuv"
  
  if not ensurePathExists(userBin):
    return InstallationResult(
      success: false,
      `method`: UserBin,
      path: userBin,
      message: "Failed to create ~/bin directory"
    )
  
  if createNiuvWrapper(targetPath, niuvExecutable):
    return InstallationResult(
      success: true,
      `method`: UserBin,
      path: targetPath,
      message: &"Installed to {targetPath}. Add ~/bin to your PATH if needed."
    )
  else:
    return InstallationResult(
      success: false,
      `method`: UserBin,
      path: targetPath,
      message: "Failed to create niuv wrapper"
    )

proc addToShellPath(directory: string): bool =
  ## Add directory to shell PATH configuration
  let shell = detectShellType()
  let configFile = getShellConfigFile(shell)
  
  if configFile == "":
    return false
  
  let pathExport = case shell
    of Fish:
      &"set -gx PATH {directory} $PATH"
    else:
      &"export PATH=\"{directory}:$PATH\""
  
  try:
    # Check if already in config
    if fileExists(configFile):
      let content = readFile(configFile)
      if directory in content:
        return true  # Already configured
    
    # Add to config file
    let configDir = parentDir(configFile)
    if not dirExists(configDir):
      createDir(configDir)
    
    # Add comment and export
    let existingContent = if fileExists(configFile): readFile(configFile) else: ""
    let newContent = existingContent & "\n# Added by niuv auto-installer\n" & pathExport & "\n"
    writeFile(configFile, newContent)
    return true
  except:
    return false

proc autoInstallNiuv*(forceReinstall: bool = false): InstallationResult =
  ## Auto-install niuv with best method detection
  
  # Check if niuv is already available
  if not forceReinstall and isExecutableInPath("niuv"):
    return InstallationResult(
      success: true,
      `method`: CurrentPath,
      path: findExe("niuv"),
      message: "niuv is already available in PATH"
    )
  
  # Find current niuv executable
  let currentNiuv = getCurrentDir() / "niuv"
  if not fileExists(currentNiuv):
    return InstallationResult(
      success: false,
      `method`: CurrentPath,
      path: currentNiuv,
      message: "niuv executable not found in current directory"
    )
  
  # Try installation methods in order of preference
  
  # 1. Try ~/.local/bin (most common)
  block localBinInstall:
    let result = installToLocalBin(currentNiuv)
    if result.success:
      # Check if ~/.local/bin is in PATH
      let localBin = expandTilde("~/.local/bin")
      if localBin notin getEnv("PATH", ""):
        if addToShellPath(localBin):
          return InstallationResult(
            success: true,
            `method`: LocalBin,
            path: result.path,
            message: result.message & " PATH updated automatically."
          )
        else:
          return InstallationResult(
            success: true,
            `method`: LocalBin,
            path: result.path,
            message: result.message & "\nPlease add 'export PATH=\"$HOME/.local/bin:$PATH\"' to your shell configuration."
          )
      else:
        return result
  
  # 2. Try ~/bin (alternative)
  block userBinInstall:
    let result = installToUserBin(currentNiuv)
    if result.success:
      let userBin = expandTilde("~/bin")
      if userBin notin getEnv("PATH", ""):
        if addToShellPath(userBin):
          return InstallationResult(
            success: true,
            `method`: UserBin,
            path: result.path,
            message: result.message & " PATH updated automatically."
          )
        else:
          return InstallationResult(
            success: true,
            `method`: UserBin,
            path: result.path,
            message: result.message & "\nPlease add 'export PATH=\"$HOME/bin:$PATH\"' to your shell configuration."
          )
      else:
        return result
  
  # 3. Fallback: manual instructions
  return InstallationResult(
    success: false,
    `method`: CurrentPath,
    path: currentNiuv,
    message: """Automatic installation failed. Please install manually:
1. Copy niuv to a directory in your PATH
2. Or add current directory to PATH: export PATH="$PWD:$PATH"
3. Or create an alias: alias niuv="$PWD/niuv"
"""
  )

proc showInstallationStatus*() =
  ## Show current installation status and suggestions
  styledEcho(fgCyan, styleBright, "niuv Installation Status")
  echo ""
  
  # Check if niuv is in PATH
  if isExecutableInPath("niuv"):
    let niuvPath = findExe("niuv")
    styledEcho(fgGreen, "✓ niuv is available at: ", fgWhite, niuvPath)
    
    # Show version if possible
    try:
      let (version, code) = execCmdEx("niuv version")
      if code == 0:
        echo "  " & version.strip()
    except:
      discard
  else:
    styledEcho(fgRed, "✗ niuv is not in PATH")
    
    # Check common installation locations
    let locations = [
      expandTilde("~/.local/bin/niuv"),
      expandTilde("~/bin/niuv"),
      "/usr/local/bin/niuv",
      getCurrentDir() / "niuv"
    ]
    
    var found = false
    for location in locations:
      if fileExists(location):
        styledEcho(fgYellow, "  Found at: ", fgWhite, location)
        found = true
    
    if not found:
      styledEcho(fgRed, "  No niuv executable found in common locations")
  
  echo ""
  
  # Show shell information
  let shell = detectShellType()
  let configFile = getShellConfigFile(shell)
  
  echo &"Shell: {shell}"
  if configFile != "":
    echo &"Config: {configFile}"
    if fileExists(configFile):
      styledEcho(fgGreen, "  ✓ Configuration file exists")
    else:
      styledEcho(fgYellow, "  ! Configuration file does not exist")
  
  echo ""
  echo "To auto-install niuv, run: niuv install-self"

proc installSelfCommand*(args: seq[string]): int =
  ## Handle 'niuv install-self' command
  var forceReinstall = false
  
  if "--help" in args or "-h" in args:
    echo """
niuv install-self - Auto-install niuv to system PATH

Usage:
  niuv install-self [options]

Options:
  --force        Force reinstallation even if already installed
  --status       Show installation status only
  --help, -h     Show this help

This command automatically:
1. Detects the best installation location
2. Creates a robust wrapper script
3. Updates shell configuration if needed
4. Handles PATH issues automatically
"""
    return 0
  
  if "--status" in args:
    showInstallationStatus()
    return 0
  
  if "--force" in args:
    forceReinstall = true
  
  styledEcho(fgCyan, styleBright, "niuv Auto-Installer")
  echo ""
  echo "Installing niuv with PATH-independent wrapper..."
  echo ""
  
  let result = autoInstallNiuv(forceReinstall)
  
  if result.success:
    styledEcho(fgGreen, styleBright, "✓ Installation successful!")
    echo ""
    styledEcho(fgWhite, "Method: ", fgCyan, $result.`method`)
    styledEcho(fgWhite, "Path: ", fgCyan, result.path)
    echo ""
    echo result.message
    echo ""
    styledEcho(fgGreen, "You can now use 'niuv' from anywhere!")
    
    # Test the installation
    echo ""
    echo "Testing installation..."
    if isExecutableInPath("niuv"):
      styledEcho(fgGreen, "✓ niuv command is available")
      try:
        let (version, code) = execCmdEx("niuv version")
        if code == 0:
          echo "  " & version.strip()
      except:
        discard
    else:
      styledEcho(fgYellow, "! You may need to restart your shell or source your configuration")
    
    return 0
  else:
    styledEcho(fgRed, styleBright, "✗ Installation failed")
    echo ""
    echo result.message
    echo ""
    styledEcho(fgCyan, "Run 'niuv install-self --status' to diagnose issues")
    return 1